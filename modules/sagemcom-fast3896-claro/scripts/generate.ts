import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { catalogDigest, fieldValueType } from "../src/discovery.ts";
import type { SchemaCatalog, SchemaNode, FieldSchema } from "../src/discovery.ts";
import { record } from "../src/protocol.ts";
import type { SourceInventory } from "./har.ts";

function tsValue(field: FieldSchema): string {
  const primitive = fieldValueType(field);
  const base = primitive === "json" ? "Json" : primitive;
  const enums = field.restrictions?.["enum-values"];
  const alternatives = Array.isArray(enums)
    ? enums.flatMap((e) =>
        record(e)
          ? [e.name, e.value]
              .filter((v): v is string | number => typeof v === "string" || typeof v === "number")
              .map((v) => JSON.stringify(v))
          : [],
      )
    : [];
  return [...new Set([base, ...alternatives])].join(" | ");
}
function pathType(node: SchemaNode): string {
  let path = node.path;
  // Longest first so the inserted template cannot change an ancestor match.
  for (const selected of [...node.selectors].sort((a, b) => b.length - a.length))
    path = path.slice(0, selected.length) + "${Selector}" + path.slice(selected.length);
  return node.selectors.length ? "`" + path + "`" : JSON.stringify(path);
}
function property(node: SchemaNode, value: string): string {
  return `  ${JSON.stringify(node.path)}: ${value};`;
}
export function generate(catalog: SchemaCatalog, sources?: SourceInventory): Map<string, string> {
  if (
    catalog.format !== 1 ||
    !Array.isArray(catalog.nodes) ||
    !catalog.nodes.length ||
    !catalog.coverage ||
    !record(catalog.identity)
  )
    throw new TypeError("invalid catalog");
  if (
    catalog.identity.Manufacturer !== "Sagemcom" ||
    catalog.identity.ModelName !== "FAST3896_CLARO" ||
    catalog.identity.ProductClass !== "FAST3896-15"
  )
    throw new TypeError("catalog must describe Sagemcom FAST3896_CLARO (FAST3896-15)");
  const profile: Record<string, string> = {};
  for (const [key, field] of Object.entries({
    manufacturer: "Manufacturer",
    model: "ModelName",
    productClass: "ProductClass",
    hardwareVersion: "HardwareVersion",
    softwareVersion: "SoftwareVersion",
    guiApiVersion: "GUIAPIVersion",
  })) {
    const value = catalog.identity[field];
    if (typeof value !== "string" || !value)
      throw new TypeError("catalog is missing a required device identity field");
    profile[key] = value;
  }
  const seen = new Set<string>();
  for (const node of catalog.nodes) {
    if (
      !/^Device(?:\/[A-Za-z_][\w:.-]*)*$/.test(node.path) ||
      !node.name ||
      !node.type ||
      !Array.isArray(node.selectors) ||
      node.selectors.some(
        (s) =>
          !node.path.startsWith(s) ||
          (node.path.length !== s.length && node.path[s.length] !== "/"),
      )
    )
      throw new TypeError("invalid schema path/selector");
    if (seen.has(node.path)) throw new TypeError("duplicate schema path");
    seen.add(node.path);
  }
  const digest = catalogDigest(catalog);
  const header = `// generated by pnpm run generate; edit inventory/firmware.json, not this file.\n// schema sha256: ${digest}\n`;
  const union = (paths: string[]) =>
    (paths.length ? paths.map((p) => "  | " + p).join("\n") : "  never") + ";";
  const lines = [
    header,
    'import type { Json } from "./protocol.ts";',
    "",
    "export type Selector = `[${string}]`;",
    "export type CanonicalPath<P extends string> = P extends `${infer Head}[${string}]${infer Tail}` ? CanonicalPath<`${Head}${Tail}`> : P;",
    "",
    "export type ModelPath =",
    union(catalog.nodes.map(pathType)),
    "",
    "export type WritablePath =",
    union(catalog.nodes.filter((n) => n.flags.value && n.flags.config).map(pathType)),
    "",
    "export type CommandPath =",
    union(
      catalog.nodes.flatMap((n) =>
        n.commands.map((c) => pathType({ ...n, path: n.path + "#" + c.name })),
      ),
    ),
    "",
    "export interface ModelValues {",
  ];
  lines.push(
    ...catalog.nodes.map((n) => property(n, tsValue(n))),
    "}",
    "",
    "export interface WritableValues {",
  );
  lines.push(
    ...catalog.nodes
      .filter((n) => n.flags.value && n.flags.config)
      .map((n) => property(n, tsValue(n))),
    "}",
    "",
  );
  const commands = catalog.nodes.flatMap((n) => n.commands.map((c) => ({ node: n, command: c })));
  const commandKeys = commands.map(({ node, command }) => node.path + "#" + command.name);
  if (new Set(commandKeys).size !== commandKeys.length)
    throw new TypeError("ambiguous command metadata");
  for (const [name, parameters] of [
    ["CommandInputs", "input"],
    ["CommandOutputs", "output"],
  ] as const) {
    lines.push(`export interface ${name} {`);
    for (const { node, command } of commands) {
      const key = JSON.stringify(node.path + "#" + command.name);
      const fields = command[parameters]
        .map((f) => `${JSON.stringify(f.name)}?: ${tsValue(f)}`)
        .join("; ");
      lines.push(`  ${key}: ${fields ? `{ ${fields} }` : "Record<string, never>"};`);
    }
    lines.push("}", "");
  }
  const docs = [
    "<!-- generated by pnpm run generate; edit inventory/firmware.json -->",
    "# Sagemcom FAST3896_CLARO API inventory",
    "",
    ...Object.entries(catalog.identity).map(([k, v]) => `- ${k}: \`${v}\``),
    "",
    `schema sha256: \`${digest}\`. ${catalog.nodes.length} nodes; ${commands.length} command signatures.`,
    "",
    "metadata is advertised, not proof that a command was executed. command inputs/outputs are optional because the metadata does not declare requiredness. list-element XPaths need selectors; empty lists may expose no element schema. see README.md for coverage and safety.",
    "",
    "## remote commands",
    "",
    "| path / method | input parameters | output parameters |",
    "| --- | --- | --- |",
    ...commands.map(
      ({ node, command }) =>
        `| \`${node.path}#${command.name}\` | ${command.input.map((f) => `\`${f.name}: ${fieldValueType(f)}\``).join(", ")} | ${command.output.map((f) => `\`${f.name}: ${fieldValueType(f)}\``).join(", ")} |`,
    ),
    "",
    "## data-model nodes",
    "",
    "config/value flags permit typed writes; actual authorization and restrictions remain router-owned. numeric enum names are accepted alongside numeric representations. the JSON catalog includes the exact restrictions.",
    "",
    "| schema path | wire type | flags |",
    "| --- | --- | --- |",
    ...catalog.nodes.map(
      (n) =>
        `| \`${n.path}\` | \`${n.type}\` | ${Object.keys(n.flags)
          .filter((k) => n.flags[k])
          .join(", ")} |`,
    ),
    "",
  ];
  if (sources)
    docs.push(
      "## shipped frontend references",
      "",
      "these literal commands were found in retained JavaScript, not necessarily advertised or authorized on this firmware. use client.call(xpath, method, parameters) for this untyped surface. source coordinates and asset digests are in inventory/sources.json.",
      "",
      ...[...new Set(sources.frontendCommands.map((c) => c.method))]
        .sort()
        .map((c) => `- \`${c}\``),
      "",
    );
  const protocol =
    header +
    `export const errorCodes = ${JSON.stringify(sources?.errorCodes ?? {}, null, 2)} as const;\nexport type XmoErrorName = keyof typeof errorCodes;\nexport type XmoErrorCode = (typeof errorCodes)[XmoErrorName];\nexport const frontendCommands = ${JSON.stringify([...new Set(sources?.frontendCommands.map((c) => c.method) ?? [])].sort(), null, 2)} as const;\nexport type FrontendCommand = (typeof frontendCommands)[number];\nexport const endpoints = ${JSON.stringify(sources?.endpoints ?? [])} as const;\nexport const wireMethods = ${JSON.stringify(sources?.wireMethods ?? [])} as const;\n`;
  return new Map([
    [
      "src/device.generated.ts",
      header +
        `export const supportedDevice = Object.freeze(${JSON.stringify(profile, null, 2)} as const);\nexport type SupportedDevice = typeof supportedDevice;\n`,
    ],
    ["src/protocol.generated.ts", protocol],
    [
      "src/catalog.generated.ts",
      header +
        'import type { SchemaCatalog } from "./discovery.ts";\n\nexport const catalog: SchemaCatalog = ' +
        JSON.stringify(catalog, null, 2) +
        ";\n",
    ],
    ["src/model.generated.ts", lines.join("\n")],
    ["API.md", docs.join("\n")],
  ]);
}
export function run(root: string, check: boolean): void {
  const catalog: SchemaCatalog = JSON.parse(
    readFileSync(`${root}/inventory/firmware.json`, "utf8"),
  );
  let stale = false;
  const sources: SourceInventory = JSON.parse(
    readFileSync(`${root}/inventory/sources.json`, "utf8"),
  );
  for (const [path, content] of generate(catalog, sources)) {
    if (check) {
      let current: string | undefined;
      try {
        current = readFileSync(`${root}/${path}`, "utf8");
      } catch {
        /* Missing outputs are stale, not repaired. */
      }
      if (current !== content) {
        console.error(`stale generated output: ${path}`);
        stale = true;
      }
    } else writeFileSync(`${root}/${path}`, content);
  }
  if (stale) throw new Error("catalog output is stale; run pnpm run generate");
}
