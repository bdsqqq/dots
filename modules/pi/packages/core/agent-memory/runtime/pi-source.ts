/** sorted object keys, ordered arrays, no whitespace; JSON values only. */
export function canonicalJSON(value: unknown): string {
  if (value === null || typeof value !== "object") {
    const json = JSON.stringify(value);
    if (json === undefined) throw new Error("expected a JSON value");
    return json;
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJSON).join(",")}]`;
  return `{${Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([k, v]) => `${JSON.stringify(k)}:${canonicalJSON(v)}`)
    .join(",")}}`;
}

function digest(value: unknown): string {
  return createHash("sha256")
    .update(canonicalJSON(value), "utf8")
    .digest("hex");
}

/** capture time and importance are scheduling metadata, not evidence identity. */
export function hashSourceWindow(
  window: Pick<SourceWindow, "source" | "scope" | "excerpts">,
): SourceHash {
  return digest({
    source: window.source,
    scope: window.scope,
    excerpts: window.excerpts,
  }) as SourceHash;
}

export function windowId(
  window: Pick<SourceWindow, "source" | "sourceHash" | "excerpts">,
): WindowId {
  return digest({
    source: window.source,
    spans: window.excerpts.map((e) => e.span),
    sourceHash: window.sourceHash,
  }) as WindowId;
}

export interface NativeSourcePolicy {
  /** explicit caller authorization, not permission inferred from a tool's output. */
  readonly authorizeTool?: (
    entry: SessionEntry,
    tool: { name: string; callId: string },
  ) => boolean;
  /** optional additional privacy filter; runs on complete parts, before splitting. */
  readonly sanitize?: (text: string) => string;
}

export type NativeSourceInput =
  | { readonly kind: "provided"; readonly snapshot: LoadedSession }
  | {
      readonly kind: "disk";
      readonly workspace: string;
      readonly source:
        | { readonly kind: "file"; readonly path: string }
        | { readonly kind: "id"; readonly sessionId: string };
      readonly rootOptions?: NativeSessionRootOptions;
    };

/** snapshotting never requires a file, including SDK --no-session managers. */
export function nativeSourceSnapshot(
  manager: Pick<SessionManager, "getHeader" | "getEntries" | "getSessionFile">,
): LoadedSession {
  const header = manager.getHeader();
  if (!header) throw new Error("native session has no header");
  return structuredClone({
    header,
    entries: manager.getEntries(),
    sessionFile: manager.getSessionFile() ?? null,
  });
}

/**
 * v1 ids generated by SDK migration are NOT immutable source ids. stable ordinal
 * locators name original linear records instead; callers must use these locators
 * for selection/continuation. v2/v3 native entry ids are preserved verbatim.
 */
export function normalizeNativeSourceEntries(
  raw: readonly FileEntry[],
): LoadedSession {
  const [originalHeader] = raw;
  if (
    !originalHeader ||
    originalHeader.type !== "session" ||
    !originalHeader.id ||
    typeof originalHeader.cwd !== "string"
  )
    throw new Error("expected a native session header");
  if (raw.slice(1).some((e) => e.type === "session"))
    throw new Error("duplicate session header");
  const legacy = (originalHeader.version ?? 1) < 2;
  const manager = SessionManager.inMemory(
    originalHeader.cwd,
    undefined,
    structuredClone([...raw]),
  );
  const header = manager.getHeader()!;
  const entries = manager.getEntries();
  if (legacy) {
    const ids = new Map(
      entries.map((entry, i) => [entry.id, `legacy-v1:record:${i + 1}`]),
    );
    for (const entry of entries) {
      const oldId = entry.id;
      entry.id = ids.get(oldId)!;
      entry.parentId =
        entry.parentId === null ? null : ids.get(entry.parentId)!;
      if (entry.type === "compaction")
        entry.firstKeptEntryId =
          ids.get(entry.firstKeptEntryId) ?? entry.firstKeptEntryId;
    }
  }
  return { header, entries, sessionFile: null };
}

/** SDK parsing/migration, but no open(), repair, or rewrite of source bytes. */
export async function loadNativeSourceSnapshot(
  path: string,
  signal?: AbortSignal,
): Promise<LoadedSession> {
  const text = await readFile(path, { encoding: "utf8", signal });
  const raw = text.split(/\r?\n/).flatMap((line, i) => {
    if (!line.trim()) return [];
    // SDK parsing skips malformed lines; fail closed rather than accept a gap.
    JSON.parse(line);
    const entries = parseSessionEntries(line);
    if (entries.length !== 1 || typeof entries[0]?.type !== "string")
      throw new Error(`invalid native session record at line ${i + 1}`);
    return entries;
  });
  return { ...normalizeNativeSourceEntries(raw), sessionFile: path };
}

function validTime(value: string): string {
  if (typeof value !== "string" || !Number.isFinite(Date.parse(value)))
    throw new Error("invalid native authored timestamp");
  return value;
}

function* textParts(
  entries: readonly SessionEntry[],
  policy: NativeSourcePolicy,
): Generator<SourceExcerpt> {
  for (const entry of entries) {
    // raw history, not model projection: summaries, custom memory injections,
    // context edits, system prompts and hidden thinking are not fresh experience.
    if (entry.type !== "message") continue;
    const message = entry.message;
    if (
      message.role !== "user" &&
      message.role !== "assistant" &&
      message.role !== "toolResult"
    )
      continue;
    const toolResult = message.role === "toolResult" ? message : null;
    if (
      toolResult &&
      !policy.authorizeTool?.(entry, {
        name: toolResult.toolName,
        callId: toolResult.toolCallId,
      })
    )
      continue;
    const content =
      typeof message.content === "string"
        ? [{ type: "text" as const, text: message.content }]
        : message.content;
    if (!Array.isArray(content))
      throw new Error("invalid native message content");
    for (const [index, part] of content.entries()) {
      let text: string;
      let identity: unknown[];
      if (part.type === "text") {
        text = part.text;
        identity = toolResult
          ? [
              "content",
              index,
              "toolResult",
              toolResult.toolCallId,
              toolResult.toolName,
              toolResult.isError,
            ]
          : ["content", index, "text"];
      } else if (part.type === "toolCall" && message.role === "assistant") {
        if (
          !policy.authorizeTool?.(entry, { name: part.name, callId: part.id })
        )
          continue;
        text = canonicalJSON(part.arguments);
        identity = ["content", index, "toolCall", part.id, part.name];
      } else continue;
      if (typeof text !== "string") throw new Error("invalid native text part");
      // offsets belong to this producer's redacted part, never the secret input.
      text = redact(text).text;
      if (policy.sanitize) text = redact(policy.sanitize(text)).text;
      if (!text) continue;
      yield {
        span: {
          entryId: entry.id as EntryId,
          partId: canonicalJSON(identity),
          start: 0,
          end: Buffer.byteLength(text),
        },
        parentEntryId: entry.parentId as EntryId | null,
        producerRole: message.role,
        occurredAt: validTime(entry.timestamp),
        text,
      };
    }
  }
}

function sameSpan(a: SourceSpan, b: SourceSpan): boolean {
  return (
    a.entryId === b.entryId &&
    a.partId === b.partId &&
    a.start === b.start &&
    a.end === b.end
  );
}

/**
 * one part per window keeps identity independent of later appended entries or
 * neighboring branches. maxWindowBytes bounds excerpt UTF-8 bytes, not JSON framing.
 * continuation must be a returned window's final span at the same byte budget.
 */
export function buildNativeSourcePage(
  request: SourceReadRequest,
  entries: readonly SessionEntry[],
  capturedAt: string,
  policy: NativeSourcePolicy = {},
): SourcePage {
  if (
    !Number.isSafeInteger(request.maxWindowBytes) ||
    request.maxWindowBytes < 4 ||
    !Number.isSafeInteger(request.maxWindows) ||
    request.maxWindows < 1
  )
    throw new Error("invalid source window limits");
  validTime(capturedAt);
  if (
    entries.at(-1)?.id !== request.throughEntryId ||
    entries.some(
      (entry, i) => entry.parentId !== (i === 0 ? null : entries[i - 1]!.id),
    )
  )
    throw new Error("expected the selected raw root-to-entry branch");
  const windows: SourceWindow[] = [];
  let found = request.after === null;
  for (const excerpt of textParts(entries, policy)) {
    const bytes = Buffer.from(excerpt.text, "utf8");
    for (let start = 0; start < bytes.length;) {
      let end = Math.min(start + request.maxWindowBytes, bytes.length);
      // a continuation byte cannot begin the next window.
      while (end < bytes.length && (bytes[end]! & 0xc0) === 0x80) end--;
      const span = { ...excerpt.span, start, end };
      start = end;
      if (!found) {
        if (sameSpan(span, request.after!)) found = true;
        continue;
      }
      if (windows.length === request.maxWindows)
        return {
          windows,
          next: windows.at(-1)!.excerpts.at(-1)!.span,
          complete: false,
        };
      const excerpts: SourceWindow["excerpts"] = [
        {
          ...excerpt,
          span,
          text: bytes.subarray(span.start, span.end).toString("utf8"),
        },
      ];
      const base = { source: request.source, scope: request.scope, excerpts };
      const sourceHash = hashSourceWindow(base);
      windows.push({
        ...base,
        sourceHash,
        windowId: windowId({ ...base, sourceHash }),
        capturedAt,
        importance: "ordinary",
      });
    }
  }
  if (!found)
    throw new Error("continuation is not in the selected branch/window budget");
  return { windows, next: null, complete: true };
}

/**
 * input ownership is explicit: provided snapshots never resolve roots or read files.
 * the request selects one raw native branch; catch-up may enumerate historical
 * leaves externally, retaining the same ids and dated parent lineage.
 */
export function nativeSourceProducer(
  input: NativeSourceInput,
  options: NativeSourcePolicy & { readonly capturedAt: string },
): SourceProducer {
  // freeze caller-owned input; an extension may keep appending to its manager.
  const owned =
    input.kind === "provided"
      ? { ...input, snapshot: structuredClone(input.snapshot) }
      : input;
  return {
    async read(request, signal) {
      signal.throwIfAborted();
      if (request.source.origin.kind !== "session")
        throw new Error("native producer requires session origin");
      const deps = {
        ...nativeHistoryDependencies,
        load: async (
          path: string,
          abort?: AbortSignal,
        ): Promise<FileEntry[]> => {
          const snapshot = await loadNativeSourceSnapshot(path, abort);
          return [snapshot.header, ...snapshot.entries];
        },
      };
      let source;
      let workspace: string;
      if (owned.kind === "provided") {
        source = { kind: "loaded" as const, session: owned.snapshot };
        workspace = owned.snapshot.header.cwd;
      } else {
        workspace = owned.workspace;
        if (owned.source.kind === "id") {
          const selection = resolveNativeSessionSelection({
            ...owned.rootOptions,
            cwd: workspace,
          });
          if (selection.kind === "flat")
            deps.discover = (dir, abort) =>
              SessionManager.list(workspace, dir, undefined, abort);
          source = { ...owned.source, sessionDir: selection.root };
        } else source = owned.source;
      }
      const branch = {
        kind: "entry" as const,
        entryId: request.throughEntryId,
      };
      const selection: ReadSessionInput =
        source.kind === "loaded"
          ? { workspace, source, branch }
          : source.kind === "file"
            ? { workspace, source, branch }
            : { workspace, source, branch };
      const result = await readSession(selection, deps, signal);
      if (!result.ok)
        throw new Error(
          `native source ${result.error.code}: ${result.error.message}`,
        );
      if (result.value.sessionId !== request.source.origin.sessionId)
        throw new Error("native session identity mismatch");
      signal.throwIfAborted();
      return buildNativeSourcePage(
        request,
        result.value.entries,
        options.capturedAt,
        options,
      );
    },
  };
}

